/// The table at `tick` (1.5 s apart): CPU% jitters around each row's mean,
/// TIME+ accrues from it, the flickering PID exists on alternating 8-tick
/// windows. The wiggle draws from its own stream seeded by `(seed, tick)`, so
/// the meters a synth publishes are the same whether or not a table tier is
/// asking for the table (same seed → same meters, D41).
pub fn proc_table(tick: u64, seed: u64) -> ProcTable {
    let mut rng = XorShift::new(seed ^ tick.wrapping_mul(0x9E37_79B9_7F4A_7C15));
    let present = (tick / 8).is_multiple_of(2);
    let rows = SET
        .iter()
        .filter(|t| !t.flicker || present)
        .map(|t| {
            let jitter = if t.cpu > 0.0 {
                (rng.jitter() as f32) * t.cpu * 0.15
            } else {
                0.0
            };
            let cpu_pct = (t.cpu + jitter).max(0.0);
            // 1.5 s per tick at `cpu` percent of one core = cpu × 1.5 cs.
            let time_cs = t.time_cs + (tick as f64 * f64::from(t.cpu) * 1.5) as u64;
            ProcRow {
                pid: t.pid,
                ppid: t.ppid,
                tgid: t.pid,
                uid: t.uid,
                user: Arc::from(t.user),
                state: t.state,
                pri: t.pri,
                nice: t.nice,
                nlwp: t.nlwp,
                virt_kib: t.virt_kib,
                res_kib: t.res_kib,
                shr_kib: t.shr_kib,
                cpu_pct,
                mem_pct: (t.res_kib as f64 / MEM_TOTAL_KIB * 100.0) as f32,
                time_cs,
                starttime: t.starttime,
                kthread: t.kthread,
                cmdline: Arc::from(if t.cmdline.is_empty() {
                    t.comm
                } else {
                    t.cmdline
                }),
                comm: Arc::from(t.comm),
            }
        })
        .collect();
    ProcTable {
        rows,
        pid_digits: PID_DIGITS,
    }
}
